"""Bounded metadata and iteration-scoped tracing without touching model outputs."""
import json
import logging
from collections.abc import Iterator
from contextlib import contextmanager
from contextvars import ContextVar
from copy import copy
from itertools import islice
from time import time_ns
from types import GeneratorType
from typing import Any, Callable

from fi_instrumentation import FITracer, TraceConfig
from opentelemetry import context, trace
from opentelemetry.context import _SUPPRESS_INSTRUMENTATION_KEY
from opentelemetry.trace import Status, StatusCode
from wrapt import ObjectProxy

_ACTIVE: ContextVar[tuple[int, ...]] = ContextVar("traceai_transformers_active", default=())
_MAX_PREVIEW = 4096
logger = logging.getLogger(__name__)
logger.addHandler(logging.NullHandler())


def _log_failure(action: str, error: Exception) -> None:
    # Telemetry is fail-open, but not silent. Do not log exception messages or
    # traceback source lines: they can bypass TraceConfig's content privacy.
    logger.warning("Transformers instrumentation failed to %s (%s)", action, type(error).__name__)


def _record_error(span, error: BaseException, config: TraceConfig) -> None:
    if config.pii_redaction or config.hide_error_details:
        # Supported FI core versions mask supplied attributes, but not the
        # message/traceback generated by record_exception or status descriptions.
        # Omit those surfaces entirely, including chained errors and notes;
        # never stringify or mutate the exception being returned to the caller.
        cls = type(error)
        exception_type = cls.__qualname__
        if cls.__module__ and cls.__module__ != "builtins":
            exception_type = f"{cls.__module__}.{exception_type}"
        span.add_event("exception", {
            "exception.type": exception_type,
            "exception.escaped": "False",
        })
        span.set_status(StatusCode.ERROR)
    else:
        span.record_exception(error)
        span.set_status(Status(StatusCode.ERROR, str(error)))


def _preview(value: object) -> str:
    # No repr/default=str, tensor conversion, custom iteration or full JSON
    # serialization of unbounded collections. A global node budget also bounds
    # nested batches, not just each individual list.
    budget = [64]

    def trim(item, depth=0):
        budget[0] -= 1
        if budget[0] < 0 or depth > 5:
            return "[truncated]"
        if type(item) is str:
            return item[:_MAX_PREVIEW]
        if item is None or type(item) in (bool, int, float):
            return item
        if type(item) in (list, tuple):
            return [trim(v, depth + 1) for v in item[:16] if budget[0] > 0]
        if type(item) is dict:
            result = {}
            for key, val in islice(item.items(), 16):
                if budget[0] <= 0 or len(result) >= 16:
                    break
                if type(key) is str:
                    result[key[:128]] = trim(val, depth + 1)
            return result
        return "[not captured]"

    return json.dumps(trim(value), ensure_ascii=True)[:_MAX_PREVIEW]


class _Invocation:
    def __init__(self, wrapper, instance, value, parent):
        self.tracer = wrapper.tracer
        self.config = wrapper.config
        self.identity = id(instance)
        self.parent = parent
        self.name = "transformers." + wrapper.task
        self.attributes = {
            "gen_ai.span.kind": wrapper.kind,
            "gen_ai.provider.name": "huggingface",
            "gen_ai.operation.name": (
                "embeddings" if wrapper.kind == "EMBEDDING" else
                "text_completion" if wrapper.kind == "LLM" else "question_answering"
            ),
            "transformers.task": wrapper.task,
        }
        # Model architecture is safe metadata, not a local filesystem path or
        # arbitrary user-supplied model identifier.
        model_type = getattr(getattr(getattr(instance, "model", None), "config", None), "model_type", None)
        if type(model_type) is str:
            self.attributes["gen_ai.request.model"] = model_type[:256]
        # Generation responses can contain the entire original prompt/chat.
        # Never re-export hidden inputs through a full-text output preview.
        self.capture_output = wrapper.capture and wrapper.kind != "EMBEDDING" and not (
            wrapper.config.hide_outputs or wrapper.config.hide_output_text or
            wrapper.config.hide_output_messages or wrapper.config.hide_inputs or
            wrapper.config.hide_input_text or wrapper.config.hide_input_messages
        )
        if wrapper.capture and not (
            wrapper.config.hide_inputs or wrapper.config.hide_input_text or
            wrapper.config.hide_input_messages
        ):
            self.attributes["input.value"] = _preview(value)
        self.span = None
        self.started = False
        self.finished = False

    def start(self, start_time=None):
        if not self.started:
            self.started = True
            try:
                self.span = self.tracer.start_span(
                    self.name, context=self.parent, attributes=self.attributes, start_time=start_time,
                )
            except Exception as error:
                # An exporter/provider failure must not prevent local inference.
                _log_failure("start span", error)
            self.attributes = None

    @contextmanager
    def activate(self):
        token = context.attach(self.parent)
        active = _ACTIVE.set((*_ACTIVE.get(), self.identity))
        try:
            self.start()
            if self.span is None:
                yield
            else:
                with trace.use_span(self.span, end_on_exit=False, record_exception=False,
                                    set_status_on_exception=False):
                    yield
        finally:
            _ACTIVE.reset(active)
            context.detach(token)

    def finish(self, error=None, output=None):
        if self.finished:
            return
        self.finished = True
        if self.span is None:
            return
        try:
            if error is not None:
                _record_error(self.span, error, self.config)
            else:
                if self.capture_output and output is not None:
                    self.span.set_attribute("output.value", _preview(output))
                self.span.set_status(StatusCode.OK)
        except Exception as telemetry_error:
            _log_failure("record span result", telemetry_error)
        finally:
            try:
                self.span.end()
            except Exception as telemetry_error:
                _log_failure("end span", telemetry_error)


class _TracedIterator(Iterator):
    """One span per lazy call, current only while the producer executes.

    Payloads are never accumulated. Close an abandoned iterator explicitly;
    finalization is only a best-effort fallback, as with Python generators.
    """
    def __init__(self, wrapped, invocation, *, iterator=None):
        self._wrapped = wrapped
        self._iterator = iterator
        self._invocation = invocation
        self._closed = False

    def __next__(self):
        if self._closed:
            raise StopIteration
        try:
            with self._invocation.activate():
                if self._iterator is None:
                    self._iterator = iter(self._wrapped)
                return next(self._iterator)
        except StopIteration:
            self._closed = True
            self._invocation.finish()
            self._wrapped = self._iterator = None
            raise
        except BaseException as error:
            self._closed = True
            self._invocation.finish(error)
            self._wrapped = self._iterator = None
            raise

    def close(self):
        if self._closed:
            return
        self._closed = True
        try:
            closer = getattr(self._wrapped, "close", None)
            if closer is not None:
                # Do not start an inference span for an unconsumed iterator.
                if self._invocation.started:
                    with self._invocation.activate():
                        closer()
                else:
                    closer()
        except BaseException as error:
            self._invocation.finish(error)
            raise
        finally:
            self._invocation.finish()
            # Release DataLoader iterators/workers and their last batch promptly.
            self._wrapped = self._iterator = None

    def __getattr__(self, name):
        return getattr(self._wrapped, name)

    def __del__(self):
        self._invocation.finish()


class _TracedDataset(ObjectProxy):
    """Keep upstream dataset protocols, with a separate span per traversal.

    PipelineIterator is an IterableDataset whose __iter__ resets its producer,
    including during a partial traversal. A one-shot Iterator wrapper loses that
    behavior. ObjectProxy preserves __len__ and isinstance(..., IterableDataset),
    which DataLoader uses to choose iterable rather than indexed access.
    """
    def __init__(self, wrapped, invocation):
        super().__init__(wrapped)
        # This template stays unstarted and retains only metadata and context,
        # not source previews, outputs, or a pipeline/model reference.
        self._self_template = invocation
        self._self_cursor = _TracedIterator(wrapped, copy(invocation))

    def __iter__(self):
        self._self_cursor.close()
        invocation = copy(self._self_template)
        try:
            iterator = iter(self.__wrapped__)
        except BaseException as error:
            invocation.start()
            invocation.finish(error)
            raise
        self._self_cursor = _TracedIterator(self.__wrapped__, invocation, iterator=iterator)
        return self

    def __next__(self):
        return next(self._self_cursor)

    def __reduce_ex__(self, protocol):
        # Pickle the native dataset, not this proxy: its invocation retains a
        # tracer provider and parent context which cannot safely cross a spawn
        # boundary (and may contain unpicklable locks or private metadata).
        # Inference in a deserialized DataLoader worker is deliberately untraced.
        return self.__wrapped__.__reduce_ex__(protocol)

    def close(self):
        # Explicit close ends the current traversal; a later iter() retains
        # the underlying dataset's own ability (or inability) to start again.
        self._self_cursor.close()


def _input(args, kwargs):
    if args:
        return args[0]
    for key in ("inputs", "text_inputs", "texts", "X"):
        if key in kwargs:
            return kwargs[key]
    # Extractive QA uses named question/context rather than a single input.
    return {key: kwargs[key] for key in ("question", "context") if key in kwargs}


def _lazy_input(value, task):
    if task == "question-answering":
        # Upstream's QA argument handler materializes its inputs eagerly.
        return False
    from torch.utils.data import Dataset
    return isinstance(value, (GeneratorType, Dataset))


class _PipelineWrapper:
    def __init__(self, *, tracer: FITracer, config: TraceConfig, capture: bool, task: str, kind: str) -> None:
        self.tracer, self.config, self.capture = tracer, config, capture
        self.task, self.kind = task, kind
        self.enabled = True

    def __call__(self, wrapped: Callable[..., Any], instance: Any,
                 args: tuple[Any, ...], kwargs: dict[str, Any]) -> Any:
        if not self.enabled or id(instance) in _ACTIVE.get() or context.get_value(_SUPPRESS_INSTRUMENTATION_KEY):
            return wrapped(*args, **kwargs)
        try:
            value = _input(args, kwargs)
            invocation = _Invocation(self, instance, value, context.get_current())
            lazy = _lazy_input(value, self.task)
        except Exception as error:
            _log_failure("prepare span metadata", error)
            return wrapped(*args, **kwargs)
        if lazy:
            # The framework sets up the iterator here but does not run inference.
            # Guard super().__call__ wrappers without creating a premature span.
            active = _ACTIVE.set((*_ACTIVE.get(), id(instance)))
            call_start = time_ns()
            try:
                result = wrapped(*args, **kwargs)
            except BaseException as error:
                invocation.start(start_time=call_start)
                invocation.finish(error)
                raise
            finally:
                _ACTIVE.reset(active)
            if isinstance(result, Iterator):
                # Do not keep even bounded source previews for lazy streams.
                invocation.attributes.pop("input.value", None)
                from torch.utils.data import IterableDataset
                if isinstance(result, IterableDataset):
                    return _TracedDataset(result, invocation)
                return _TracedIterator(result, invocation)
            # Some framework/backend paths materialize the result; avoid
            # consuming or transforming it to manufacture lazy behavior.
            invocation.start(start_time=call_start)
            invocation.finish(output=result)
            return result
        try:
            with invocation.activate():
                result = wrapped(*args, **kwargs)
        except BaseException as error:
            invocation.finish(error)
            raise
        invocation.finish(output=result)
        return result
