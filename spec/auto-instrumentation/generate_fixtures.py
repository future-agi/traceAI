# Small standard-library contract oracle: independent of SDK extraction and of the
# explicitly supplied golden numbers above. It verifies A8 projections on the
# legacy cases too, and replays chunk arrival associations for the new A10 cases.
def merge_snapshot(target, source):
    for key, value in source.items():
        if isinstance(value, dict):
            if not isinstance(target.get(key), dict):
                target[key] = {}
            merge_snapshot(target[key], value)
        else:
            target[key] = value  # null and zero replace prior values too


def number(mapping, key, optional=False):
    if key not in mapping:
        return 0 if optional else None
    value = mapping[key]
    return value if type(value) is int and value >= 0 else None


def inclusive(mapping, base, *additions):
    values = [number(mapping, base)] + [number(mapping, key, optional=True) for key in additions]
    return None if any(value is None for value in values) else sum(values)


def normalize_usage(family, raw):
    details = {}
    raw_total = number(raw, "total_tokens")
    if family == "anthropic":
        input_count = inclusive(raw, "input_tokens", "cache_read_input_tokens", "cache_creation_input_tokens")
        output_count = number(raw, "output_tokens")
        details = {"cache_read": number(raw, "cache_read_input_tokens"), "cache_write": number(raw, "cache_creation_input_tokens")}
    elif family == "bedrock.converse":
        input_count = inclusive(raw, "inputTokens", "cacheReadInputTokens", "cacheWriteInputTokens")
        output_count, raw_total = number(raw, "outputTokens"), number(raw, "totalTokens")
        details = {"cache_read": number(raw, "cacheReadInputTokens"), "cache_write": number(raw, "cacheWriteInputTokens")}
    elif family == "gemini":
        input_count = inclusive(raw, "promptTokenCount", "toolUsePromptTokenCount")
        output_count = inclusive(raw, "candidatesTokenCount", "thoughtsTokenCount")
        raw_total = number(raw, "totalTokenCount")
        details = {"cache_read": number(raw, "cachedContentTokenCount"), "reasoning": number(raw, "thoughtsTokenCount")}
    else:
        ikey, okey = ("prompt_tokens", "completion_tokens") if "prompt_tokens" in raw or "completion_tokens" in raw else ("input_tokens", "output_tokens")
