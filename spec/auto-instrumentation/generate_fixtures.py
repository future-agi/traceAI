def observed_chunks(response, encoded):
    """Apply the transport partition/failure boundary before any frame extraction."""
    wire = b"".join(encoded)
    sizes = response.get("chunk_sizes", [len(chunk) for chunk in encoded])
    assert all(type(size) is int and size >= 0 for size in sizes)
    assert sum(sizes) == len(wire), "chunk sizes must partition the complete wire body"
    offsets = response.get("arrival_offsets_ms")
    if offsets is not None:
        assert len(sizes) == len(offsets)
        assert all(type(offset) in (int, float) and offset >= 0 for offset in offsets)
        assert offsets == sorted(offsets), "arrival offsets must be monotonic"
    else:
        offsets = [None] * len(sizes)
    observed_count = response.get("error_after_chunks", len(sizes))
    assert type(observed_count) is int and observed_count >= 0
    start = 0
    for index, (size, offset) in enumerate(zip(sizes, offsets)):
        if index >= observed_count:
            break
        chunk, start = wire[start:start + size], start + size
        yield offset, chunk


def observed_sse(response):
    """Replay only complete SSE frames from observed chunks, with arrival times.

    A partial frame never becomes an event, even if its JSON payload is already
    complete. Untimed baseline streams use the same byte framing for usage.
    """
    pending = b""
    for offset, chunk in observed_chunks(response, [sse_bytes(event) for event in response["sse"]]):
        pending += chunk
        events = []
        while b"\n\n" in pending:
            frame, pending = pending.split(b"\n\n", 1)
            lines = frame.splitlines()
            payload = b"\n".join(line[5:].lstrip(b" ") for line in lines if line.startswith(b"data:"))
            if payload == b"[DONE]" or not payload:
                continue
            event = json.loads(payload)
            if isinstance(event, dict):
                for line in lines:
                    if line.startswith(b"event:"):
                        event["event"] = line[6:].strip().decode("utf-8")
            events.append(event)
        yield offset, chunk, events


def observed_json(response):
    """Replay a JSON object or complete members of a streamed top-level array.

    Decode UTF-8 incrementally so a partial later codepoint cannot hide already
    complete members. JSONDecoder handles nested braces/arrays and escaped quotes;
    never inspect the hypothetical unobserved suffix to decide frame completeness.
    An array member's closing brace completes that member independently of the
    array's later comma/closing bracket. A partial object contributes nothing.
    """
    if "json" not in response:
        return
    utf8 = codecs.getincrementaldecoder("utf-8")()
    decoder = json.JSONDecoder()
    pending, state = "", "start"
    for offset, chunk in observed_chunks(response, [json_bytes(response["json"])]):
        pending += utf8.decode(chunk)
        events = []
        while state != "done":
            pending = pending.lstrip(" \t\r\n")
            if not pending:
                break
            if state == "start":
                if pending.startswith("["):
                    pending, state = pending[1:], "array_value"
                    continue
                state = "single_value"
            if state == "array_separator":
                if pending.startswith(","):
                    pending, state = pending[1:], "array_value"
                    continue
                if pending.startswith("]"):
                    state = "done"
                break
            if state == "array_value" and pending.startswith("]"):
                state = "done"
                break
            try:
                event, end = decoder.raw_decode(pending)
            except json.JSONDecodeError:
                break
            events.append(event)
            pending = pending[end:]
            state = "array_separator" if state == "array_value" else "done"
        if state == "done":
            pending = ""
        yield offset, chunk, events


def observed_ndjson(response):
    """Replay complete newline-delimited JSON records, not partial JSON payloads.

    Keep bytes until the newline arrives, including split UTF-8 codepoints. Apply
    the shared chunk partition/failure boundary first; an incomplete final line
    never becomes an observed event, even if its closing brace already arrived.
    """
    pending = b""
    for offset, chunk in observed_chunks(response, [ndjson_bytes(event) for event in response["ndjson"]]):
        pending += chunk
        events = []
        while b"\n" in pending:
            line, pending = pending.split(b"\n", 1)
            if line.strip():
                events.append(json.loads(line))
        yield offset, chunk, events


def observed_frames(response):
    # A8 and A10 share the transport boundary for SSE, NDJSON and JSON.
    if "sse" in response:
        return observed_sse(response)
    if "ndjson" in response:
        return observed_ndjson(response)
    return observed_json(response)


def raw_usage(fixture, family):
    events = (event for _, _, frames in observed_frames(fixture["response"]) for event in frames)
    raw = {}
    for event in events:
        if not isinstance(event, dict):
            continue
        sources = [event]
        for key in ("message", "response"):
            if isinstance(event.get(key), dict):
                sources.append(event[key])
        for source in sources:
            usage = source.get("usageMetadata" if family == "gemini" else "usage")
            if isinstance(usage, dict):
                merge_snapshot(raw, usage)
    return raw


def nonempty(value):
    return isinstance(value, str) and len(value) > 0


def tool_output(function, arguments="arguments"):
    """Names and argument deltas qualify; IDs and empty scaffolds do not.

    Gemini/Ollama (and Cohere v1 parameters) can carry decoded argument objects
    rather than JSON strings. Only nonempty objects qualify without a name.
    """
    if not isinstance(function, dict):
        return False
    value = function.get(arguments)
    return nonempty(function.get("name")) or nonempty(value) or (isinstance(value, dict) and bool(value))


def tool_calls_output(calls):
    if isinstance(calls, dict):
        calls = [calls]
    return any(isinstance(call, dict) and tool_output(call.get("function")) for call in calls or [])


def content_output(content):
    """String or typed text/thinking parts, with one Mistral thinking-text level.

    Walk only model-content fields, never arbitrary nested metadata/tool results.
    A list, type tag, citation, or empty thinking block alone is not output.
    """
    if nonempty(content):
        return True
    parts = [content] if isinstance(content, dict) else content if isinstance(content, list) else []
    for part in parts:
        if not isinstance(part, dict) or part.get("type") not in (None, "text", "thinking"):
            continue
        if nonempty(part.get("text")) or nonempty(part.get("thinking")):
            return True
        thinking = part.get("thinking")
        if isinstance(thinking, list) and any(
                isinstance(piece, dict) and piece.get("type") == "text" and nonempty(piece.get("text"))
                for piece in thinking):
            return True
    return False


def first_output(event):
    if not isinstance(event, dict):
        return False
    # OpenAI Completions text and Chat deltas (not outer response metadata).
    for choice in event.get("choices") or []:
        if nonempty(choice.get("text")):
            return True
        delta = choice.get("delta") or {}
        if content_output(delta.get("content")) or any(
                nonempty(delta.get(key)) for key in ("refusal", "reasoning_content", "reasoning")):
            return True
        audio = delta.get("audio") or {}
        if any(nonempty(audio.get(key)) for key in ("data", "transcript")):
            return True
        if tool_calls_output(delta.get("tool_calls")) or tool_output(delta.get("function_call")):
            return True
    kind = event.get("type") or event.get("event_type") or event.get("event")
    # Responses tool names can precede argument deltas in output_item.added.
    if kind == "response.output_item.added":
        item = event.get("item") or {}
        if item.get("type") in ("function_call", "tool_call", "custom_tool_call", "mcp_call") and (
                tool_output(item) or tool_output(item.get("function"))):
            return True
        if item.get("type") == "custom_tool_call" and nonempty(item.get("input")):
            return True
        if item.get("type") == "code_interpreter_call" and nonempty(item.get("code")):
            return True
    if kind in ("response.output_text.delta", "response.refusal.delta", "response.reasoning_text.delta",
                "response.reasoning_summary_text.delta", "response.function_call_arguments.delta",
                "response.mcp_call_arguments.delta", "response.code_interpreter_call_code.delta",
                "response.custom_tool_call_input.delta", "response.audio.delta",
                "response.audio.transcript.delta") and nonempty(event.get("delta")):
        return True
    # Anthropic text, thinking, tool block/name and partial arguments.
    if kind == "content_block_start":
        block = event.get("content_block") or {}
        if any(nonempty(block.get(key)) for key in ("text", "thinking")) or (
                block.get("type") in ("tool_use", "server_tool_use", "mcp_tool_use") and nonempty(block.get("name"))):
            return True
    if kind == "content_block_delta":
        delta = event.get("delta") or {}
        if any(nonempty(delta.get(key)) for key in ("text", "thinking", "partial_json")):
            return True
    # Gemini thought=true marks reasoning text; the boolean alone is not output.
    for candidate in event.get("candidates") or []:
        for part in (candidate.get("content") or {}).get("parts") or []:
            if nonempty(part.get("text")) or tool_output(part.get("functionCall"), "args"):
                return True
            code = part.get("executableCode") or {}
            if isinstance(code, dict) and nonempty(code.get("code")):
                return True
            inline = part.get("inlineData") or part.get("inline_data") or {}
            mime = inline.get("mimeType") or inline.get("mime_type")
            if isinstance(mime, str) and mime.lower().startswith("audio/") and nonempty(inline.get("data")):
                return True
    # Bedrock Converse's decoded event payloads (binary framing is separate).
    delta = (event.get("contentBlockDelta") or {}).get("delta") or {}
    if nonempty(delta.get("text")) or tool_output(delta.get("toolUse"), "input"):
        return True
    if nonempty((delta.get("reasoningContent") or {}).get("text")):
        return True
    start = (event.get("contentBlockStart") or {}).get("start") or {}
    if tool_output(start.get("toolUse"), "input"):
        return True
    # Cohere v2 content/tool deltas and v1 NDJSON/SSE events. The SSE event
    # header can supply the kind when JSON omits its redundant type field.
    if kind in ("content-start", "content-delta", "tool-call-start", "tool-call-delta", "tool-plan-delta"):
        message = (event.get("delta") or {}).get("message") or {}
        if kind in ("content-start", "content-delta"):
            if content_output(message.get("content")):
                return True
        elif kind == "tool-plan-delta":
            if nonempty(message.get("tool_plan")):
                return True
        elif tool_calls_output(message.get("tool_calls")):
            return True
    if kind == "tool-calls-generation":
        if any(tool_output(call, "parameters") for call in event.get("tool_calls") or []):
            return True
    if kind == "tool-calls-chunk":
        delta = event.get("tool_call_delta")
        if nonempty(event.get("text")) or tool_output(delta, "parameters") or (
                isinstance(delta, dict) and nonempty(delta.get("text"))):
            return True
    if kind == "text-generation" and nonempty(event.get("text")):
        return True
    # Ollama records are untyped. Do not mistake a typed keep-alive/error event's
    # informational message/response string for model output (or call .get on it).
    if kind is None:
        message = event.get("message")
        if isinstance(message, dict) and (
                any(nonempty(message.get(key)) for key in ("content", "thinking"))
                or tool_calls_output(message.get("tool_calls"))):
            return True
        if nonempty(event.get("response")) or nonempty(event.get("thinking")):
            return True
    # Cartesia TTS SSE emits generated base64 audio in chunk.data, not audio.data.
    return kind == "chunk" and nonempty(event.get("data"))


def arrival_milestones(response):
    assert "arrival_offsets_ms" in response
    result = {}
    for offset, chunk, events in observed_frames(response):
        if not chunk:
            continue
        result.setdefault(FIRST_CHUNK, round(offset / 1000, 6))
        if any(first_output(event) for event in events):
            result.setdefault(FIRST_TEXT, round(offset / 1000, 6))
    return result


def check_contract():
    usage_checked, timing_checked = 0, 0
    for fixture in cases:
        if not fixture["expect"]["captured"]:
            continue
        expected = fixture["expect"]
        family = family_of(fixture)
        if family:
            actual = normalize_usage(family, raw_usage(fixture, family))
            for key, want in expected.get("attributes", {}).items():
                if key in USAGE_ATTRIBUTES.values():
                    assert actual.get(key) == want, f"{fixture['name']}: {key}: {actual.get(key)!r} != {want!r}"
            for key in expected.get("absent", []):
                if key in USAGE_ATTRIBUTES.values():
                    assert key not in actual, f"{fixture['name']}: unexpected {key}"
            usage_checked += 1
        if "arrival_offsets_ms" in fixture["response"]:
            actual = arrival_milestones(fixture["response"])
            for key in (FIRST_CHUNK, FIRST_TEXT):
                if key in expected["attributes"]:
                    assert actual.get(key) == expected["attributes"][key], f"{fixture['name']}: wrong {key}"
                elif key in expected.get("absent", []):
                    assert key not in actual, f"{fixture['name']}: unexpected {key}"
                else:
                    raise AssertionError(f"{fixture['name']}: milestone expectation must be explicit: {key}")
            timing_checked += 1
    print(f"A8 usage projections: {usage_checked} passed; A10 arrival replays: {timing_checked} passed")


def check_round6_privacy():
    # The S6 generator's 47-case proof is intentionally frozen. Review new cases
    # here with an independent exact allowlist, rather than weakening that proof.
    spec = Path(__file__).resolve().parent
    privacy = runpy.run_path(str(spec / "generate_privacy_fixtures.py"))
    reference = privacy["Reference"](json.loads((spec / "privacy.json").read_text()))
    allowed = {
        ("milestone-generated-audio-not-played", "response.sse.1.choices.0.delta.audio.data"),
        ("milestone-gemini-generated-audio", "response.sse.1.candidates.0.content.parts.0.inlineData.data"),
        ("milestone-gemini-empty-audio-no-output", "response.sse.1.candidates.0.content.parts.0.inlineData.data"),
        ("milestone-cartesia-sse-generated-audio", "response.sse.1.data"),
        ("milestone-a10-chat-audio-data-positive", "response.sse.1.choices.0.delta.audio.data"),
        ("milestone-a10-chat-audio-data-positive", "response.sse.2.choices.0.delta.audio.data"),
        ("milestone-a10-chat-audio-data-empty", "response.sse.1.choices.0.delta.audio.data"),
        ("milestone-a10-responses-audio-data-positive", "response.sse.2.delta"),
    }
    changed, metrics = set(), 0
    for fixture in cases[LEGACY_COUNT:]:
        secrets = reference.harvest(fixture["request"])
        for side in ("request", "response"):
            source = fixture[side]
            for field in ("headers", "url", "json", "text", "sse", "ndjson", "multipart", "binary"):
                if field not in source:
                    continue
                original = source[field]
                cleaned = reference.scrub(original, secrets=secrets)
                for path, _ in privacy["changed_leaves"](original, cleaned, side + "." + field):
                    identity = fixture["name"], path
                    assert identity in allowed, f"round6 privacy false positive: {identity}"
                    changed.add(identity)
        for key, value in fixture["expect"]["attributes"].items():
            assert reference.scrub(value, key, secrets=secrets) == value, f"round6 expected attribute scrubbed: {fixture['name']} {key}"
            if key.startswith("gen_ai.usage."):
                metrics += 1
        for key in ("name", "status_description"):
            if key in fixture["expect"]:
                value = fixture["expect"][key]
                assert reference.scrub(value, secrets=secrets) == value, f"round6 expected {key} scrubbed: {fixture['name']}"
    assert changed == allowed, "round6 audio omission no longer exercised"
    print(f"Round6 privacy preservation: {len(cases) - LEGACY_COUNT} passed; {metrics} token metrics retained; {len(changed)} intentional audio omissions")


